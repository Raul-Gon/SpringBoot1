package com.miempresa.ifcd0021test25.dto;

public class PokemonSimpleDto {
	
	private int id;
	private int height;
	private int weight;
	private String name;
	private String tralara;
	
	
	public PokemonSimpleDto() {
	}
	
	public int getId() {
		return id;
	}

	public void setId(int id) {
		this.id = id;
	}

	public int getHeight() {
		return height;
	}

	public void setHeight(int height) {
		this.height = height;
	}

	public int getWeight() {
		return weight;
	}

	public void setWeight(int weight) {
		this.weight = weight;
	}

	public String getName() {
		return name;
	}

	public void setName(String name) {
		this.name = name;
	}

	public String getTralara() {
		return tralara;
	}

	public void setTralara(String tralara) {
		this.tralara = tralara;
	}

}
